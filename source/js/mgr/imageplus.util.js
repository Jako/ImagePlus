/**
 * Image+ Utilities
 *
 * @package imageplus
 * @subpackage script
 */

/**
 * Apply the defaults to the config, if the config value is not set, empty or zero
 */
ImagePlus.util.applyDefaults = function (config, defaults) {
    Ext.iterate(defaults, function (key, value) {
        if (config[key] === undefined || config[key] === null || config[key] === '' || config[key] === 0) {
            config[key] = value;
        }
    });
    return config;
};

/**
 * Get the value object from a value, that is an object, a JSON encoded object or a path
 */
ImagePlus.util.parseFileValue = function (value) {
    if (typeof value === 'string') {
        if (value.charAt(0) === '{') {
            try {
                return JSON.parse(value) || {};
            } catch (e) {
                return {};
            }
        }
        return value ? {image: value} : {};
    }
    return value || {};
};

/**
 * Get the url of a thumbnail generated by the Image+ thumbnail processor. Without a media source, the thumbnail
 * processor searches the media sources of the Image+ template variables for the image.
 */
ImagePlus.util.thumbUrl = function (src, source, size) {
    var params = Ext.apply({
        action: 'mgr/image/thumbnail',
        HTTP_MODAUTH: MODx.siteId,
        src: src
    }, size || {w: 100});
    if (source) {
        params.source = source;
    }
    return ImagePlus.config.connectorUrl + '?' + new URLSearchParams(params).toString();
};

/**
 * Get the url of a media source path, that can be used in the manager
 */
ImagePlus.util.sourceUrl = function (source) {
    var url = (ImagePlus.config.sources && ImagePlus.config.sources[source]) ? ImagePlus.config.sources[source].url : '';
    return ImagePlus.util.sourceObjectUrl(url) || MODx.config.base_url;
};

/**
 * Get the url of a media source object, that can be used in the manager. Root relative and absolute urls are used
 * as they are, other urls are relative to the base url.
 */
ImagePlus.util.sourceObjectUrl = function (url) {
    if (!url) {
        return '';
    }
    return (/^(https?:)?\/\//.test(url) || url.charAt(0) === '/') ? url : MODx.config.base_url + url;
};

/**
 * Format a size like "1280x720" or a proportion like "16x9" with spaces around the x
 */
ImagePlus.util.formatDimensions = function (dimensions) {
    return (dimensions) ? String(dimensions).replace(/(\d)\s*x\s*(\d)/i, '$1 x $2') : '';
};

/**
 * Get the reduced proportion of a width and a height like "16 x 9"
 */
ImagePlus.util.formatProportion = function (width, height) {
    var gcd = function (a, b) {
        return b ? gcd(b, a % b) : a;
    };
    var divisor = gcd(width, height);
    return (width / divisor) + ' x ' + (height / divisor);
};

/**
 * Load an image and get its pixel dimensions. The promise is resolved with null, if the image can't be loaded.
 */
ImagePlus.util.loadImageDimensions = function (url) {
    return new Promise(function (resolve) {
        var image = new Image();
        image.onload = function () {
            resolve({width: image.naturalWidth, height: image.naturalHeight});
        };
        image.onerror = function () {
            resolve(null);
        };
        image.src = url;
    });
};

/**
 * Normalize the crop size configurations. "ratio" is accepted as alias of "proportion". It is removed,
 * because the crop window and the saved crops use "ratio" for the calculated aspect ratio.
 */
ImagePlus.util.normalizeCropSizes = function (sizes) {
    var normalized = {};
    Ext.iterate(sizes || {}, function (key, size) {
        size = Ext.apply({}, size);
        if (size.ratio !== undefined) {
            size.proportion = size.proportion || size.ratio;
            delete size.ratio;
        }
        normalized[key] = size;
    });
    return normalized;
};
